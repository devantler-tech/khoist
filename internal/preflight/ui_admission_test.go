// Removing the delivered field-level rejection must not let either publisher
// report format accept a new legacy UI declaration (#443).
func TestDeliveredSchemaRejectsNewUIDeclarations(t *testing.T) {
	t.Parallel()
	for _, version := range []string{"", "data-product-ui/v1", "data-product-ui/v2"} {
		t.Run(version, func(t *testing.T) {
			t.Parallel()
			p := product("stage-one")
			control := bundle(t, p)
			if r := check(t, control); !r.Valid || !r.Complete || len(r.Descriptors) != 1 {
				t.Fatalf("UI-free declaration rejected: %+v", r)
			}
			if r := selected(t, control); !r.Valid || !r.Complete || len(r.Descriptors) != 1 {
				t.Fatalf("UI-free v2 declaration rejected: %+v", r)
			}
			p.Spec.UI = &data.ProductUI{
				URL: "https://ui.example.test/PRIVATE_PATH", Title: "PRIVATE_TITLE",
			}
			if version != "" {
				p.Spec.UI.Contract = &data.UIContract{
					APIVersion:   version,
					HostOrigins:  []data.UIHostOrigin{"https://host.example.test"},
					Capabilities: []data.UICapability{"status", "resize"},
				}
			}
			selection := bundle(t, p)
			v1 := check(t, selection)
			if v1.Valid || len(v1.Descriptors) != 0 {
				t.Fatalf("delivered schema accepted new legacy UI in v1: %+v", v1)
			}
			requireCode(t, v1, "AdmissionInvalid")
			v2 := selected(t, selection)
			diagnostic := richCode(t, v2, "CrossFieldInvalid")
			if v2.Valid || len(v2.Descriptors) != 0 || v2.Plan != nil ||
				diagnostic.Path != "/spec/ui" {
				t.Fatalf("delivered schema accepted or misidentified new legacy UI in v2: %+v", v2)
			}
			if err := reportSchema(t).Validate(reportValue(t, v2)); err != nil {
				t.Fatalf("UI rejection changed the v2 report contract: %v", err)
			}
			for _, report := range []any{v1, v2} {
				encoded, err := json.Marshal(report)
				if err != nil || strings.Contains(string(encoded), "PRIVATE_") {
					t.Fatal("UI rejection disclosed submitted metadata")
				}
			}
		})
	}
}

// historicalUIReport reads a saved report generated by the frozen v8 source,
// rather than trying to recreate an unsupported declaration with today's CRD.
func historicalUIReport(t *testing.T, protocol string) BundleReport {
	t.Helper()
	var encoded []byte
	var err error
	switch protocol {
	case "v1":
		encoded, err = os.ReadFile("testdata/khoist-v8-ui-protocol-v1-preflight-v2.json")
	case "v2":
		encoded, err = os.ReadFile("testdata/khoist-v8-ui-protocol-v2-preflight-v2.json")
	default:
		t.Fatal("unsupported historical UI protocol fixture")
	}
	if err != nil {
		t.Fatal(err)
	}
	var report BundleReport
	if err := json.Unmarshal(encoded, &report); err != nil {
		t.Fatal(err)
	}
	if report.APIVersion != "data-product-preflight/v2" || !report.Valid || !report.Complete ||
		len(report.Descriptors) != 1 {
		t.Fatal("historical fixture is not a complete v2 publisher report")
	}
	var descriptor struct {
		UI *data.ProductUI `json:"ui"`
	}
	if err := json.Unmarshal(report.Descriptors[0], &descriptor); err != nil {
		t.Fatal(err)
	}
	if descriptor.UI == nil || descriptor.UI.Contract == nil ||
		descriptor.UI.Contract.APIVersion != "data-product-ui/"+protocol {
		t.Fatal("historical fixture lost its declared UI protocol")
	}
	if err := reportSchema(t).Validate(reportValue(t, report)); err != nil {
		t.Fatalf("historical report no longer satisfies its retained schema: %v", err)
	}
	return report
}
